// Unified catalogue, real browser rendering and synthetic-pad checks. No hardware claim.
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'C:/Users/luker/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
;(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const captures = path.join(__dirname, '../.audit-input/verification')
  fs.mkdirSync(captures, { recursive: true })
  try {
    const page = await browser.newPage()
    page.setDefaultTimeout(12000)
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto(process.env.JSM_TEST_URL || 'http://127.0.0.1:1421/?mock')
    await page.waitForFunction(() => window.__pad && document.querySelector('.app-shell'))
    const keep = page.getByRole('button', { name: 'Keep them', exact: true })
    if (await keep.count()) await keep.click()
    const open = async kind => {
      await page.evaluate(request => { const detail = typeof request === 'string' ? { kind: request, input: 'S', value: request === 'key' ? 'SPACE' : '' } : request; window.__pickerResult = []; window.dispatchEvent(new CustomEvent('jsm:picker', { detail })) }, kind)
      await page.locator('[data-picker="actions"]').waitFor()
      await page.waitForTimeout(300)
    }
    const picker = page.locator('[data-picker="actions"]')
    for (const theme of ['dark', 'light']) for (const [width, height] of [[1440, 900], [900, 600]]) {
      await page.setViewportSize({ width, height })
      await page.evaluate(theme => document.documentElement.dataset.theme = theme, theme)
      await open('controller')
      await picker.locator('[data-category="Rumble"]').click()
      await page.waitForTimeout(350)
      const geometry = await picker.evaluate(root => {
        const group = root.querySelector('.action-picker__groups').getBoundingClientRect()
        const action = root.querySelector('.action-picker__content button').getBoundingClientRect()
        const footer = root.querySelector('footer').getBoundingClientRect()
        return { gap: action.top - group.bottom, footerBottom: footer.bottom, overflow: root.scrollWidth > root.clientWidth }
      })
      assert.ok(geometry.gap >= 0 && geometry.gap <= 32, JSON.stringify(geometry))
      assert.ok(geometry.footerBottom <= height + 1, 'footer stays reachable')
      assert.equal(geometry.overflow, false, 'no horizontal page overflow')
      await page.screenshot({ path: path.join(captures, `picker-rumble-${theme}-${width}.png`) })
      await picker.getByRole('button', { name: 'Cancel', exact: true }).click()
    }
    await open('key')
    assert.equal(await picker.getByRole('searchbox').count(), 1, 'search always visible')
    await picker.locator('[data-family="mouse"]').click()
    await picker.locator('[data-token="LMOUSE"]').click()
    await picker.waitFor({ state: 'detached' })
    assert.deepEqual(await page.evaluate(() => window.__pickerResult[0].patch), { outputKind: 'mouse', outputValue: 'LMOUSE' })
    await open('key')
    await picker.locator('[data-customize]').click()
    await page.locator('[data-picker="combo"]').waitFor()
    assert.ok(await page.locator('[data-combo-key]').count(), 'key modifiers remain available')
    await page.keyboard.press('x')
    await picker.waitFor()
    await picker.getByRole('button', { name: 'Cancel', exact: true }).click()
    assert.deepEqual(await page.evaluate(() => window.__pickerResult), [], 'returning from key combo does not write a binding')
    await open('key')
    await picker.locator('[data-customize]').click()
    await page.locator('[data-combo-use]').click()
    assert.deepEqual(await page.evaluate(() => window.__pickerResult[0].combo), ['LCONTROL', 'SPACE'])
    await open('gamepad')
    await picker.locator('[data-customize]').click()
    await page.locator('[data-picker="gamepad"] [data-category="DS4"]').click()
    await page.locator('[data-picker="gamepad"] [data-logical="faceSouth"]').click()
    assert.deepEqual(await page.evaluate(() => window.__pickerResult[0]), { enable: 'DS4' })
    assert.equal(await page.evaluate(() => window.__pickerResult[1].patch.outputValue), 'PS_CROSS')
    await open({ kind: 'mode', input: 'LSL', source: { kind: 'layerAction', action: { input: '!LSL', verb: 'toggle', layerId: 'veh' } } })
    await picker.locator('.action-grid--layers button').nth(1).click()
    assert.deepEqual(await page.evaluate(() => window.__pickerResult[0].patch.layerAction), { input: '!LSL', verb: 'toggle', layerId: 'map' }, 'changing layer preserves its activation')
    await open('controller')
    await picker.locator('[data-category="Rumble"]').click()
    await picker.locator('[data-customize]').click()
    await page.locator('[data-picker="controller"] [data-action="haptic"]').click()
    await page.locator('[data-picker="haptic"] [data-param-use]').click()
    assert.equal(await page.evaluate(() => window.__pickerResult[0].patch.outputKind), 'haptic', 'haptic parameter editor remains reachable')
    for (const kind of ['key', 'mouse', 'gamepad', 'menu', 'mode', 'controller', 'config', 'command']) {
      await open(kind)
      await page.keyboard.press('Escape')
      await picker.waitFor({ state: 'detached' })
    }
    await open('controller')
    await page.evaluate(() => window.__pad.press(['N']))
    await page.waitForTimeout(200)
    assert.ok(await picker.getByRole('searchbox').evaluate(node => node === document.activeElement))
    await picker.getByRole('searchbox').fill('zzznomatch')
    await picker.getByRole('searchbox').press('Escape')
    assert.equal(await picker.getByRole('searchbox').inputValue(), '')
    await picker.getByRole('button', { name: 'Cancel', exact: true }).click()
    assert.deepEqual(errors, [])
    console.log('Unified picker passed: eight entry kinds, direct mouse selection, key combo, pad search, Escape, dark/light at 1440×900 and 900×600.')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
