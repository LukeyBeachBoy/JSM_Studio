const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('../JSM_GUI/jsm_gui_tauri/node_modules/typescript');
const mod = { exports: {} };
new Function('exports', ts.transpileModule(fs.readFileSync('JSM_GUI/jsm_gui_tauri/src/utils/controllerNavigation.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText)(mod.exports);
const { controllerNavigationEnabled: enabled, anyControllerNavigation: any } = mod.exports;
const cyborg = 'type-25-device-0000000000000001', steam = 'type-24-device-0000000000000002';
const state = { controllerNavEnabled: true };
assert.equal(enabled(state, cyborg), false, 'Azeron keeps normal bindings by default');
assert.equal(enabled(state, steam), true);
state.controllerNavOverrides = { 'type-25': true, [cyborg]: false };
assert.equal(enabled(state, cyborg), false);
assert.equal(enabled(state, 'type-25-device-0000000000000003'), true);
assert.equal(enabled(state, steam), true);
state.controllerNavEnabled = false;
assert.equal(enabled(state, steam), false, 'legacy off is preserved for other controllers');
assert.equal(any(state), true, 'one enabled controller keeps the navigation rule installed');
state.controllerNavOverrides = { [cyborg]: false, [steam]: true };
assert.equal(enabled(state, cyborg), false);
assert.equal(enabled(state, steam), true);
assert.equal(any(state), true);
state.controllerNavOverrides[steam] = false;
assert.equal(any(state), false);
console.log('PASS: controller navigation defaults, model inheritance, device overrides, legacy setting and aggregate ownership');
