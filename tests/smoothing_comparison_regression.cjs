const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const Module = require('node:module')
const APP = path.join(__dirname, '../JSM_GUI/jsm_gui_tauri')
const ts = require(path.join(APP, 'node_modules/typescript'))
const cache = new Map()
function load(file) {
  if (cache.has(file)) return cache.get(file).exports
  const mod = new Module(file); cache.set(file, mod)
  mod.filename = file; mod.paths = Module._nodeModulePaths(path.dirname(file))
  mod.require = name => name.startsWith('.') ? load(path.resolve(path.dirname(file), name + '.ts')) : require(require.resolve(name, { paths: [APP] }))
  mod._compile(ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, file)
  return mod.exports
}
const { replaySmoothing, readSteadyingSettings } = load(path.join(APP, 'src/utils/gyroSteadiness.ts'))
const s = readSteadyingSettings('GYRO_SMOOTH_THRESHOLD = 100\nGYRO_SMOOTH_TIME = 0.12\nTICK_TIME = 3')
const input = Array.from({ length: 201 }, (_, i) => ({ at: i * 3, x: i % 2 ? 12 : -12, y: i % 3 ? 8 : -8 }))
const off = replaySmoothing(input, { ...s, smoothTime: 0 })
assert.ok(off.every(f => f.x === f.filteredX && f.y === f.filteredY), 'off must be exact, not separated for display')
const out = replaySmoothing(input, s)
const power = (frames, filtered) => frames.slice(60).reduce((sum, f) => sum + (filtered ? f.filteredX ** 2 + f.filteredY ** 2 : f.x ** 2 + f.y ** 2), 0)
assert.ok(power(out, true) < power(out, false) * .2, 'both signed jitter components are smoothed')
const step = Array.from({ length: 201 }, (_, i) => ({ at: i * 3, x: i < 60 ? 0 : i < 120 ? 12 : -12, y: 0 }))
const delayed = replaySmoothing(step, s)
assert.ok(delayed[60].filteredX > 0 && delayed[60].filteredX < 12, 'step shows partial response')
assert.ok(delayed[120].filteredX > 0 && delayed[120].x < 0, 'reversal preserves signed lag, even when speeds match')
const shorter = replaySmoothing(input, { ...s, smoothTime: .03 })
assert.notDeepEqual(out.map(f => f.filteredX), shorter.map(f => f.filteredX), 'configuration changes replay the same input')
assert.deepEqual(replaySmoothing(input, { ...s, cutoff: 90, recovery: 100 }), out, 'smoothing comparison excludes steadying range')
const irregular = replaySmoothing([{ at: 10, x: 2, y: -3 }, { at: 22, x: -4, y: 5 }, { at: 40, x: 8, y: 9 }], { ...s, smoothTime: 0 })
assert.equal(irregular.find(f => f.at === 19).x, 2)
assert.equal(irregular.find(f => f.at === 22).x, -4)
assert.equal(irregular.at(-1).at, 40)
console.log('PASS: exact bypass, signed jitter/step/reversal, setting replay, cutoff exclusion and real timestamp spacing')
