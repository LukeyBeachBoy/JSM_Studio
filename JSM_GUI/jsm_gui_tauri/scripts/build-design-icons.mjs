// Regenerates the icon and glyph modules from the design handoff:
//   design/handoff/designs/icons/{ui,modes}/*.svg  -> src/components/icons/iconData.ts
//   design/handoff/designs/icons/app/*.svg         -> src/assets/app-icon*.svg
//   design/handoff/designs/glyphs/_data.json       -> src/components/glyphs/glyphData.ts
//   design/handoff/designs/Controller Live.dc.html -> src/components/controllerArt.ts
//
// The handoff SVGs carry a C2PA manifest several KB long; only the drawing is
// kept. UI and mode icons all share one root (24 grid, stroke currentColor,
// round caps), so just their inner markup is stored and <Icon> supplies the
// root with an optical stroke width for the rendered size.
//
// Run: node scripts/build-design-icons.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, basename } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const designs = join(root, 'design/handoff/designs')

const stripMetadata = svg => svg
  .replace(/<metadata>[\s\S]*?<\/metadata>/g, '')
  .replace(/\s*xmlns:c2pa="[^"]*"/g, '')
  .trim()

const inner = svg => stripMetadata(svg).replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim()

const readSet = dir => Object.fromEntries(
  readdirSync(join(designs, 'icons', dir))
    .filter(file => file.endsWith('.svg'))
    .sort()
    .map(file => [basename(file, '.svg'), inner(readFileSync(join(designs, 'icons', dir, file), 'utf8'))]),
)

const ui = readSet('ui')
const modes = readSet('modes')

const banner = '// Generated by scripts/build-design-icons.mjs from design/handoff. Do not edit.\n'
const literal = value => JSON.stringify(value, null, 2)

writeFileSync(join(root, 'src/components/icons/iconData.ts'), `${banner}
/** UI icons (HANDOFF.md, "Icons and glyphs"): 24 grid, stroke currentColor. */
export const UI_ICONS = ${literal(ui)} as const

/** Mode and category icons, same grammar as the UI set. */
export const MODE_ICONS = ${literal(modes)} as const

export type UiIconName = keyof typeof UI_ICONS
export type ModeIconName = keyof typeof MODE_ICONS
export type IconName = UiIconName | ModeIconName
`)

for (const file of ['jsm-studio.svg', 'jsm-studio-16.svg']) {
  const svg = stripMetadata(readFileSync(join(designs, 'icons/app', file), 'utf8'))
  writeFileSync(join(root, 'src/assets', file.replace('jsm-studio', 'app-icon')), svg + '\n')
}

const data = JSON.parse(readFileSync(join(designs, 'glyphs/_data.json'), 'utf8'))
// Steam entries are [label, JSM id, inner markup]; the key is the design's own
// short name, which is not always the JSM token (LS vs LEFT_STICK), so the
// module is keyed by the design key and InputGlyph maps commands onto it.
const steam = Object.fromEntries(Object.entries(data.S).map(([key, [label, id, svg]]) => [key, { label, id, svg }]))
const families = Object.fromEntries(Object.entries(data.FAM).map(([family, { name, items }]) =>
  [family, { name, items: Object.fromEntries(items.map(([label, svg]) => [label, svg])) }]))

// Small cuts (20px and below): larger single-character labels, no inner
// detail, heavier outlines. Keyed by the file name, which is the design key.
const smallDir = join(designs, 'glyphs/steam/small')
const steamSmall = Object.fromEntries(readdirSync(smallDir).filter(file => file.endsWith('.svg')).sort()
  .map(file => [basename(file, '.svg'), inner(readFileSync(join(smallDir, file), 'utf8'))]))

writeFileSync(join(root, 'src/components/glyphs/glyphData.ts'), `${banner}
/** Steam Controller glyphs by design key: label, JSM id and inner SVG markup
 *  (24 grid). Knocked-out marks use var(--glyph-ink). */
export const STEAM_GLYPHS: Record<string, { label: string; id: string; svg: string }> = ${literal(steam)}

/** Small cuts for 20px and below, by design key. Missing keys are derived
 *  from a sibling in InputGlyph (N from S, R from L, and so on). */
export const STEAM_SMALL_GLYPHS: Record<string, string> = ${literal(steamSmall)}

/** Face buttons and shoulders for the other controller families. */
export const FAMILY_GLYPHS: Record<string, { name: string; items: Record<string, string> }> = ${literal(families)}
`)

// The Steam Controller in the approved tonal rendering (Controller Art 9c),
// front and back, exactly as Controller Live draws it. Only the art layers are
// kept; the live hotspots are drawn by ControllerStatusSvg.
const live = readFileSync(join(designs, 'Controller Live.dc.html'), 'utf8')
const artOf = className => {
  const match = live.match(new RegExp(`<svg class="${className}"[^>]*>([\\s\\S]*?)</svg>`))
  if (!match) throw new Error(`Controller Live: no ${className}`)
  return match[1].trim()
}
writeFileSync(join(root, 'src/components/controllerArt.ts'), `${banner}
/** Steam Controller front, tonal body: 1117 × 750 viewBox, themed by --art-*. */
export const STEAM_FRONT_ART = ${JSON.stringify(artOf('controller-live__art'))}

/** Steam Controller back: 428 × 319 viewBox, drawn mirrored so it reads from the front. */
export const STEAM_BACK_ART = ${JSON.stringify(artOf('controller-live__back-art'))}
`)

console.log(`icons: ${Object.keys(ui).length} ui, ${Object.keys(modes).length} modes; glyphs: ${Object.keys(steam).length} steam`)
