// Emits src/styles/accents.css: one block per accent (data-accent on <html>)
// for dark and light. Each accent takes its primary from the JSM Evolved mark
// of that colour (Brand JSM Evolved.dc.html) and re-hues the blue-grey
// surfaces, selection fill and focus ring to sit with it, at the same
// lightness and chroma as the handoff tokens so nothing else moves.
//
//   node scripts/build-accent-tokens.cjs
const fs = require('node:fs')
const path = require('node:path')

// --- sRGB <-> OKLCH -------------------------------------------------------
const lin = c => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4)
const gam = c => (c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055)
const hex2rgb = h => [1, 3, 5].map(i => parseInt(h.slice(i, i + 2), 16) / 255)
const rgb2hex = rgb => '#' + rgb.map(c => Math.round(Math.min(1, Math.max(0, c)) * 255).toString(16).padStart(2, '0')).join('')
function toOklch(hex) {
  const [r, g, b] = hex2rgb(hex).map(lin)
  const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b)
  const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b)
  const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b)
  const L = 0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s
  const a = 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s
  const bb = 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s
  const C = Math.hypot(a, bb)
  let H = (Math.atan2(bb, a) * 180) / Math.PI
  if (H < 0) H += 360
  return { L, C, H }
}
function fromOklch({ L, C, H }) {
  const a = C * Math.cos((H * Math.PI) / 180), bb = C * Math.sin((H * Math.PI) / 180)
  const l = (L + 0.3963377774 * a + 0.2158037573 * bb) ** 3
  const m = (L - 0.1055613458 * a - 0.0638541728 * bb) ** 3
  const s = (L - 0.0894841775 * a - 1.291485548 * bb) ** 3
  const r = 4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s
  const g = -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s
  const b = -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s
  return rgb2hex([r, g, b].map(gam))
}
const rehue = (hex, H, chromaScale = 1) => { const c = toOklch(hex); return fromOklch({ L: c.L, C: c.C * chromaScale, H }) }
const rgba = (hex, a) => { const [r, g, b] = hex2rgb(hex).map(c => Math.round(c * 255)); return `rgba(${r}, ${g}, ${b}, ${a})` }
const mix = (a, b, t) => { const A = hex2rgb(a), B = hex2rgb(b); return rgb2hex(A.map((c, i) => c * (1 - t) + B[i] * t)) }

// --- The marks' colours (src/assets/brand/jsm-evolved-*.svg) --------------
const ACCENTS = {
  cyan:   { tint: '#9fd6f5', base: '#3e9fd8', deep: '#175c93', ink: '#175c93', nudge: {} },
  teal:   { tint: '#bff8ec', base: '#2fd8bb', deep: '#0b6e61', ink: '#0c7f6f', nudge: { 'layer-2': 140 } },
  amber:  { tint: '#ffe9b8', base: '#f5a623', deep: '#8a5200', ink: '#9a5c00', nudge: { 'layer-3': 30 }, warnHue: 48 },
  violet: { tint: '#ddd3ff', base: '#8b6ff5', deep: '#3f28a8', ink: '#4a2fc0', nudge: { 'layer-1': 250 } },
}

// The handoff neutrals (design-tokens.css), re-hued per accent.
const DARK = {
  'surface-frame': '#0d1217', 'surface-canvas': '#131920', 'surface-nav': '#181f27', 'surface-row': '#1f2730',
  'surface-row-hover': '#26303a', 'surface-control': '#2e3844', 'surface-control-hover': '#38444f',
  'surface-sunken': '#0f151b', 'surface-raised': '#232c36',
  'text-1': '#e8eef4', 'text-2': '#b0bcc8', 'text-3': '#808c99', 'text-4': '#5b6571',
  'art-body': '#1c242d', 'art-well': '#0e1419', 'art-cap': '#212a34', 'art-line': '#e3eaf1', 'art-detail': '#aebbc8',
}
const LIGHT = {
  'surface-frame': '#e6ebf0', 'surface-canvas': '#f1f4f7', 'surface-nav': '#e9eef2', 'surface-row-hover': '#f5f8fa',
  'surface-control': '#e3e9ef', 'surface-control-hover': '#d7dfe7', 'surface-sunken': '#e4e9ee',
  'text-1': '#141c24', 'text-2': '#3e4b58', 'text-3': '#66727f', 'text-4': '#929ca7',
  'art-line': '#1c2732', 'art-detail': '#4b5967', 'art-well': '#d3dbe3', 'art-cap': '#eef2f5',
}

const lines = []
lines.push(`/* Generated by scripts/build-accent-tokens.cjs. Do not edit by hand.
   Accent themes (Appearance page): data-accent on <html> picks one of the four
   JSM Evolved marks, and these blocks give the app that mark's colour as its
   primary, with the neutrals re-hued to match (same L and C as the handoff
   tokens, hue from the mark). Cyan is the default: the handoff neutrals as
   they are, with the mark's base as the accent. */
`)
for (const [id, a] of Object.entries(ACCENTS)) {
  const hue = toOklch(a.base).H
  const dark = [
    `  --accent: ${a.base};`,
    `  --accent-strong: ${mix(a.base, a.deep, 0.35)};`,
    `  --accent-soft: ${rgba(a.base, 0.14)};`,
    `  --accent-tint: ${a.tint};`,
    `  --accent-deep: ${a.deep};`,
    `  --focus-controller: ${mix(a.base, a.tint, 0.5)};`,
    `  --focus-keyboard: ${a.base};`,
    `  --origin-override: ${a.base};`,
    `  --surface-selected: ${fromOklch({ L: 0.37, C: 0.06, H: hue })};`,
    `  --text-on-accent: #07131d;`,
    `  --command-soft: ${rgba(a.base, 0.14)};`,
    `  --command-line: ${rgba(a.base, 0.3)};`,
  ]
  const light = [
    `  --accent: ${a.ink};`,
    `  --accent-strong: ${mix(a.ink, '#000000', 0.15)};`,
    `  --accent-soft: ${rgba(a.ink, 0.1)};`,
    `  --accent-tint: ${a.tint};`,
    `  --accent-deep: ${a.deep};`,
    `  --focus-controller: ${a.ink};`,
    `  --focus-keyboard: ${a.ink};`,
    `  --origin-override: ${a.ink};`,
    `  --surface-selected: ${fromOklch({ L: 0.9, C: 0.05, H: hue })};`,
    `  --text-on-accent: #ffffff;`,
    `  --command-soft: ${rgba(a.ink, 0.1)};`,
    `  --command-line: ${rgba(a.ink, 0.3)};`,
  ]
  if (id !== 'cyan') {
    for (const [k, v] of Object.entries(DARK)) dark.push(`  --${k}: ${rehue(v, hue, 0.6)};`)
    for (const [k, v] of Object.entries(LIGHT)) light.push(`  --${k}: ${rehue(v, hue, 0.6)};`)
    dark.push(`  --surface-scrim: ${rgba(rehue('#05090d', hue), 0.64)};`)
    light.push(`  --surface-scrim: ${rgba(rehue('#14202c', hue), 0.32)};`)
    const shadow = rehue('#14283c', hue)
    light.push(`  --shadow-menu: 0 12px 32px ${rgba(shadow, 0.16)}, 0 0 0 1px var(--line-2);`)
    light.push(`  --shadow-capsule: 0 6px 20px ${rgba(shadow, 0.14)}, 0 0 0 1px var(--line-1);`)
    light.push(`  --shadow-lift: 0 1px 4px ${rgba(shadow, 0.12)};`)
  }
  // A layer hue that would sit on top of the accent moves over (design notes).
  for (const [layer, h] of Object.entries(a.nudge)) {
    dark.push(`  --${layer}: oklch(76% .11 ${h}); --${layer}-soft: oklch(76% .11 ${h} / .16); --${layer}-ink: oklch(86% .07 ${h});`)
    light.push(`  --${layer}: oklch(52% .13 ${h}); --${layer}-soft: oklch(52% .13 ${h} / .12); --${layer}-ink: oklch(40% .12 ${h});`)
  }
  if (a.warnHue) {
    dark.push(`  --warn: oklch(79% .12 ${a.warnHue}); --warn-soft: oklch(79% .12 ${a.warnHue} / .14);`)
    light.push(`  --warn: oklch(50% .14 ${a.warnHue}); --warn-soft: oklch(50% .14 ${a.warnHue} / .12);`)
  }
  // Dark blocks must not outrank the light theme: the accent block is later in
  // the cascade at the same specificity as :root[data-theme="light"], so it is
  // scoped to not-light rather than relying on the light block to repeat every key.
  const sel1 = id === 'cyan'
    ? `:root, :root[data-theme="dark"], :root[data-accent="cyan"], :root[data-accent="cyan"][data-theme="dark"]`
    : `:root[data-accent="${id}"]:not([data-theme="light"])`
  const sel2 = id === 'cyan'
    ? `:root[data-theme="light"], :root[data-accent="cyan"][data-theme="light"]`
    : `:root[data-accent="${id}"][data-theme="light"]`
  lines.push(`/* ${id} */\n${sel1} {\n${dark.join('\n')}\n}\n${sel2} {\n${light.join('\n')}\n}\n`)
}
fs.writeFileSync(path.resolve(__dirname, '../src/styles/accents.css'), lines.join('\n'))
console.log('wrote src/styles/accents.css')
